class Database {
  constructor() {
    this.dbFile = DB_FILE;
    this.ensureDirectory();
    this.load();
  }

  ensureDirectory() {
    if (!fs.existsSync(DB_DIR)) {
      fs.mkdirSync(DB_DIR, { recursive: true });
    }
  }

  load() {
    if (!fs.existsSync(this.dbFile)) {
      this.data = {
        sessions: [...SEED_SESSIONS],
        analyses: { ...SEED_ANALYSES },
        reproductions: { ...SEED_REPRODUCTIONS },
        fixes: { ...SEED_FIXES },
        regressions: [...SEED_REGRESSIONS]
      };
      this.persist();
    } else {
      try {
        const raw = fs.readFileSync(this.dbFile, 'utf8');
        this.data = JSON.parse(raw);
        if (!this.data.sessions) this.data.sessions = [];
        if (!this.data.analyses) this.data.analyses = {};
        if (!this.data.reproductions) this.data.reproductions = {};
        if (!this.data.fixes) this.data.fixes = {};
        if (!this.data.regressions) this.data.regressions = [];
      } catch (err) {
        console.error('Failed to parse database file, resetting to initial state:', err);
        this.data = { ...INITIAL_STATE };
        this.persist();
      }
    }
  }

  persist() {
    try {
      this.ensureDirectory();
      const tmp = `${this.dbFile}.tmp.${Date.now()}`;
      fs.writeFileSync(tmp, JSON.stringify(this.data, null, 2), 'utf8');
      fs.renameSync(tmp, this.dbFile);
    } catch (err) {
      console.error('Error persisting database:', err);
    }
  }

  getSessions() {
    return [...this.data.sessions];
  }

  getSessionById(id) {
    return this.data.sessions.find(s => s.id === id) || null;
  }

  createSession(payload) {
    const id = `sess_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
    const session = {
      id,
      title: payload.title || "Untitled Bug Report",
      severity: payload.severity || "Medium",
      component: payload.component || "general",
      environment: payload.environment || "Node.js v20 / Default Environment",
      error_logs: payload.error_logs || "",
      stack_trace: payload.stack_trace || "",
      steps_to_reproduce: payload.steps_to_reproduce || "",
      expected_behavior: payload.expected_behavior || "",
      actual_behavior: payload.actual_behavior || "",
      status: "created",
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString()
    };
    this.data.sessions.unshift(session);
    this.persist();
    return session;
  }

  updateSessionStatus(id, status) {
    const session = this.getSessionById(id);
    if (session) {
      session.status = status;
      session.updated_at = new Date().toISOString();
      this.persist();
    }
    return session;
  }

  getAnalysis(sessionId) {
    return this.data.analyses[sessionId] || null;
  }

  saveAnalysis(sessionId, analysis) {
    this.data.analyses[sessionId] = {
      ...analysis,
      session_id: sessionId,
      is_simulated: true,
      simulation_label: "SIMULATED AI ROOT CAUSE ENGINE"
    };
    this.persist();
    return this.data.analyses[sessionId];
  }

  getReproduction(sessionId) {
    return this.data.reproductions[sessionId] || null;
  }

  saveReproduction(sessionId, reproduction) {
    this.data.reproductions[sessionId] = {
      ...reproduction,
      session_id: sessionId,
      execution_mode: "SIMULATED_SANDBOX",
      simulation_label: "SIMULATED EXECUTION ENVIRONMENT"
    };
    this.persist();
    return this.data.reproductions[sessionId];
  }

  getFix(sessionId) {
    return this.data.fixes[sessionId] || null;
  }

  saveFix(sessionId, fix) {
    this.data.fixes[sessionId] = {
      ...fix,
      session_id: sessionId
    };
    this.persist();
    return this.data.fixes[sessionId];
  }

  getRegressions() {
    return [...this.data.regressions];
  }

  getRegressionById(id) {
    return this.data.regressions.find(r => r.id === id) || null;
  }

  addRegression(reg) {
    const id = `reg_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`;
    const regression = {
      id,
      session_id: reg.session_id,
      test_name: reg.test_name || `test_regression_${Date.now()}`,
      test_code: reg.test_code || "// Automated regression test",
      component: reg.component || "general",
      status: reg.status || "untested",
      execution_count: reg.execution_count || 0,
      last_run_at: reg.last_run_at || null,
      last_result: reg.last_result || "Never executed"
    };
    this.data.regressions.unshift(regression);
    this.persist();
    return regression;
  }

  updateRegression(id, updates) {
    const reg = this.getRegressionById(id);
    if (reg) {
      Object.assign(reg, updates);
      this.persist();
    }
    return reg;
  }

  // Telemetry Operations
  saveTelemetry(payload) {
    const id = `telem_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`;
    const telemetry = {
      id,
      session_id: payload.session_id || null,
      error_name: payload.error_name || 'UnhandledError',
      error_message: payload.error_message || '',
      stack_trace: payload.stack_trace || '',
      component: payload.component || 'client',
      network_logs: payload.network_logs || [],
      console_logs: payload.console_logs || [],
      user_breadcrumbs: payload.user_breadcrumbs || [],
      environment: payload.environment || {},
      created_at: new Date().toISOString()
    };
    if (!this.data.telemetries) this.data.telemetries = [];
    this.data.telemetries.unshift(telemetry);
    this.persist();
    return telemetry;
  }

  getTelemetries() {
    return this.data.telemetries || [];
  }

  // Pull Request Operations
  createPullRequest(payload) {
    if (!this.data.pull_requests) this.data.pull_requests = [];
    const prNumber = 100 + this.data.pull_requests.length + 1;
    const pr = {
      id: `pr_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`,
      pr_number: prNumber,
      session_id: payload.session_id,
      title: payload.title || `Fix issue in ${payload.target_file || 'core'}`,
      description: payload.description || 'Automated Pull Request synthesized by Gemini AI Bot.',
      branch: payload.branch || `bot/fix-${Date.now().toString(36)}`,
      target_branch: payload.target_branch || 'main',
      target_file: payload.target_file || 'services/checkout.js',
      patch_diff: payload.patch_diff || '',
      steps_to_reproduce: payload.steps_to_reproduce || [],
      developer_suggestion: payload.developer_suggestion || '',
      status: 'open', // open, merged, closed
      author: 'Gemini AI Debugging Bot',
      created_at: new Date().toISOString(),
      merged_at: null,
      verification_status: 'VERIFIED_BY_TEST_RUN'
    };
    this.data.pull_requests.unshift(pr);
    this.persist();
    return pr;
  }

  getPullRequests() {
    return this.data.pull_requests || [];
  }

  getPullRequestById(id) {
    return (this.data.pull_requests || []).find(p => p.id === id || String(p.pr_number) === String(id)) || null;
  }

  getPullRequestBySession(sessionId) {
    return (this.data.pull_requests || []).find(p => p.session_id === sessionId) || null;
  }

  mergePullRequest(id) {
    const pr = this.getPullRequestById(id);
    if (!pr) return null;
    pr.status = 'merged';
    pr.merged_at = new Date().toISOString();
    pr.merge_commit = `commit_${Date.now().toString(16)}_${Math.random().toString(36).substring(2, 8)}`;
    this.persist();
    return pr;
  }
}

module.exports = new Database();
