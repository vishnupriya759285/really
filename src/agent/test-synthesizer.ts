import { BugTwinTrace } from '../tracer/types';
import { RootCauseAnalysis } from './analyzer';
import { OpenAIClientWrapper } from './openai-client';

export interface SynthesizedTest {
  filename: string;
  testCode: string;
  testFramework: 'node:test' | 'jest';
  description: string;
}

export class TestSynthesizer {
  private client: OpenAIClientWrapper;

  constructor(client: OpenAIClientWrapper) {
    this.client = client;
  }

  public async synthesize(
    trace: BugTwinTrace,
    analysis: RootCauseAnalysis,
    sourceFiles: Record<string, string>
  ): Promise<SynthesizedTest> {
    const filename = `bugtwin-${trace.traceId.slice(-6)}.test.js`;

    if (!this.client.isConfigured()) {
      return this.heuristicFallback(filename, trace, analysis, sourceFiles);
    }

    const systemPrompt = `You are BugTwin's Regression Test Synthesizer.
Your mission is to generate a deterministic, self-contained automated regression test using Node.js's standard 'node:test' and 'node:assert/strict' runner.
Requirements:
1. The test MUST reproduce the exact failure described in the trace and root-cause analysis.
2. It must be 100% deterministic (mock any network or external dependencies if needed).
3. It must cleanly import the local code from the project.
4. Output valid JSON conforming to:
{
  "filename": "${filename}",
  "description": "Short explanation of what this test verifies",
  "testCode": "complete JavaScript / Node.js test file content"
}`;

    const userPrompt = `### ROOT CAUSE ANALYSIS
${JSON.stringify(analysis, null, 2)}

### TRACE ERROR
- Message: ${trace.error?.message}
- Stack: ${trace.error?.stack}

### RECORDED NETWORK CALLS (${trace.networkCalls.length})
${JSON.stringify(trace.networkCalls, null, 2)}

### RELEVANT SOURCE FILES
${Object.entries(sourceFiles)
  .map(([name, code]) => `--- FILE: ${name} ---\n${code}`)
  .join('\n\n')}

Generate the deterministic regression test file now. Return strict JSON.`;

    try {
      const responseText = await this.client.completePrompt(systemPrompt, userPrompt);
      const jsonMatch = responseText.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0]);
        return {
          filename,
          testCode: parsed.testCode || parsed.code,
          testFramework: 'node:test',
          description: parsed.description || 'Synthesized regression test'
        };
      }
    } catch (err: any) {
      console.warn(`[BugTwin Test Synthesizer] OpenAI failed: ${err.message}. Using fallback template.`);
    }

    return this.heuristicFallback(filename, trace, analysis, sourceFiles);
  }

  private heuristicFallback(
    filename: string,
    trace: BugTwinTrace,
    analysis: RootCauseAnalysis,
    sourceFiles: Record<string, string>
  ): SynthesizedTest {
    // Determine the likely target module
    let targetFile = 'index.js';
    for (const file of Object.keys(sourceFiles)) {
      if (trace.command && trace.command.includes(file)) {
        targetFile = file;
        break;
      }
      if (analysis.failingComponent && analysis.failingComponent.includes(file)) {
        targetFile = file;
        break;
      }
    }
    if (!targetFile && Object.keys(sourceFiles).length > 0) {
      targetFile = Object.keys(sourceFiles)[0];
    }

    const cleanPath = targetFile.replace(/\\/g, '/');

    const testCode = `// Generated by BugTwin Autonomous Agent
// Target Bug: ${analysis.summary}
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('path');
const { spawnSync } = require('child_process');

test('BugTwin Regression: ${analysis.summary.replace(/'/g, "\\'")}', async () => {
  // Setup environment matching trace
  process.env.BUGTWIN_REPRO = 'true';

  const targetPath = path.resolve(__dirname, '${cleanPath}');
  let subject;
  try {
    subject = require(targetPath);
  } catch (err) {
    subject = null;
  }

  if (subject && typeof subject.processPayment === 'function') {
    const result = await subject.processPayment({
      customerId: 'cust_regression_test',
      customerEmail: 'test@example.com',
      cardNumber: '4000-1234-5678-9010',
      amount: 50000,
      currency: 'JPY'
    });
    assert.ok(result, 'Expected valid transaction result without crash');
    assert.equal(result.status, 'success');
  } else if (subject && typeof subject === 'function') {
    const result = await subject();
    assert.ok(result, 'Expected valid response without crash');
  } else {
    // Execute command script directly
    const runResult = spawnSync(process.execPath, [targetPath], {
      env: { ...process.env, BUGTWIN_TEST_RUN: 'true' },
      encoding: 'utf8'
    });
    assert.equal(
      runResult.status,
      0,
      \`Regression test failed! Script crashed with exit code \${runResult.status}:\\n\${runResult.stderr || runResult.stdout}\`
    );
  }
});
`;

    return {
      filename,
      testCode,
      testFramework: 'node:test',
      description: `Automated regression test asserting fix for ${analysis.summary}`
    };
  }
}
